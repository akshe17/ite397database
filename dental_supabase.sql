-- ---------------------------------------------------------------------
-- Helper: replaces MySQL's "ON UPDATE CURRENT_TIMESTAMP" on updated_date
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_updated_date()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_date := now();
  RETURN NEW;
END;
$$;

