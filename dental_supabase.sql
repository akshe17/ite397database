CREATE OR REPLACE VIEW public.v_batch_stock_drift
WITH (security_invoker = true) AS
SELECT b.batch_id,
       b.item_id,
       b.batch_number,
       b.current_stock,
       COALESCE(SUM(m.quantity), 0) AS ledger_stock,
       b.current_stock - COALESCE(SUM(m.quantity), 0) AS difference
FROM public.inventory_batches b
LEFT JOIN public.stock_movements m ON m.batch_id = b.batch_id
GROUP BY b.batch_id, b.item_id, b.batch_number, b.current_stock
HAVING b.current_stock <> COALESCE(SUM(m.quantity), 0);

CREATE OR REPLACE VIEW public.v_billing_balance
WITH (security_invoker = true) AS
SELECT bl.billing_id,
       bl.receipt_number,
       bl.treatment_id,
       bl.billing_status_id,
       bl.total_amount,
       COALESCE(it.items_total, 0) AS items_total,
       bl.total_amount <> COALESCE(it.items_total, 0) AS total_mismatch,
       COALESCE(pm.paid_amount, 0) AS paid_amount,
       bl.total_amount - COALESCE(pm.paid_amount, 0) AS balance_due
FROM public.billings bl
LEFT JOIN (
  SELECT billing_id, SUM(subtotal) AS items_total
  FROM public.billing_items
  GROUP BY billing_id
) it ON it.billing_id = bl.billing_id
LEFT JOIN (
  SELECT p.billing_id, SUM(p.amount) AS paid_amount
  FROM public.payments p
  JOIN public.payment_statuses ps
    ON ps.status_id = p.status_id AND ps.status_name = 'Completed'
  GROUP BY p.billing_id
) pm ON pm.billing_id = bl.billing_id;

CREATE OR REPLACE VIEW public.v_item_stock
WITH (security_invoker = true) AS
SELECT i.item_id,
       i.item_name,
       i.item_category_id,
       i.low_stock_threshold,
       COALESCE(SUM(b.current_stock), 0) AS total_stock,
       COALESCE(SUM(b.current_stock), 0) <= i.low_stock_threshold AS is_low_stock,
       MIN(CASE WHEN b.current_stock > 0 THEN b.expiry_date END) AS nearest_expiry
FROM public.inventory_items i
LEFT JOIN public.inventory_batches b
  ON b.item_id = i.item_id AND b.is_archived = false
WHERE i.is_archived = false
GROUP BY i.item_id, i.item_name, i.item_category_id, i.low_stock_threshold;

